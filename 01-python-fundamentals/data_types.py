# Data Types in Python
## Python has several built-in data types that are used to store different kinds of data.
#basic types
# int, float, complex, bool,string 
print(type(10)) # int #1e307
print(type(10.5)) # float #1e308
print(type(3+4j)) # complex #1e308
print(type(True)) # bool #1e308
print(type("Hello")) # string #1e308
print('Hello')
print("""Hello""")

#container types
# list, tuple, set, dict
print([1,2,3,4])
print((1,2,3,4))
print({1,2,3,4})
print({"name":"John","age":30})#searching fast 

